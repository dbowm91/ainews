"""Build script for CSS bundling and JS minification."""
import subprocess
import sys


def bundle_css():
    """Bundle CSS files by inlining @import statements."""
    css_files = [
        'static/css/variables.css',
        'static/css/base.css',
        'static/css/layout.css',
        'static/css/components.css',
        'static/css/articles.css',
        'static/css/pages.css',
        'static/css/utilities.css',
    ]

    output_file = 'static/css/style.bundled.css'

    with open(output_file, 'w') as out:
        out.write('/* ainews - Bundled CSS */\n')
        out.write('/* Generated by scripts/build_assets.py */\n\n')

        for css_file in css_files:
            with open(css_file, 'r') as f:
                content = f.read()
            out.write(f'/* ===== {css_file} ===== */\n\n')
            out.write(content)
            out.write('\n\n')

    print(f'Bundled CSS written to {output_file}')


def bundle_js():
    """Minify and bundle JS files using esbuild."""
    import tempfile
    import os

    js_files = [
        'static/js/app.js',
        'static/js/theme.js',
        'static/js/toast.js',
        'static/js/admin.js',
    ]

    output_file = 'static/js/bundle.min.js'

    try:
        with tempfile.NamedTemporaryFile(mode='w', suffix='.js', delete=False) as tmp:
            for f in js_files:
                with open(f) as fp:
                    tmp.write(fp.read())
                    tmp.write('\n')
            tmp_path = tmp.name

        try:
            result = subprocess.run(
                ['npx', 'esbuild', tmp_path,
                 '--bundle', '--minify', '--sourcemap',
                 f'--outfile={output_file}'],
                capture_output=True,
                text=True,
                check=True,
            )
            print(f'Bundled JS written to {output_file}')
            if result.stderr:
                print(result.stderr, file=sys.stderr)
        finally:
            os.unlink(tmp_path)
        if result.stderr:
            print(result.stderr, file=sys.stderr)
    except subprocess.CalledProcessError as e:
        print(f'esbuild failed: {e.stderr}', file=sys.stderr)
        sys.exit(1)
    except FileNotFoundError:
        print('esbuild not found. Run: npm install', file=sys.stderr)
        sys.exit(1)


if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'css':
        bundle_css()
    elif len(sys.argv) > 1 and sys.argv[1] == 'js':
        bundle_js()
    else:
        bundle_css()
        bundle_js()