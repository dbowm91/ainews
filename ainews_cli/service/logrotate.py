"""Logrotate rule rendering engine."""

from __future__ import annotations

from pathlib import Path

from ainews_cli.service.models import LogrotateRuleSpec, RenderedLogrotateRule

_GENERATOR_COMMENT = "# Generated by ainews service manager — do not edit manually"


def render_logrotate_rule(spec: LogrotateRuleSpec) -> RenderedLogrotateRule:
    """Render a LogrotateRuleSpec into a logrotate config file content string."""
    lines: list[str] = []

    lines.append(spec.log_paths[0] if len(spec.log_paths) == 1 else " ".join(spec.log_paths))
    lines.append("{")

    body: list[str] = []
    body.append(f"    {spec.frequency}")
    if spec.size:
        body.append(f"    size {spec.size}")
    if spec.maxsize:
        body.append(f"    maxsize {spec.maxsize}")
    body.append(f"    rotate {spec.rotate_count}")
    if spec.compress:
        body.append("    compress")
    if spec.delay_compress:
        body.append("    delaycompress")
    if spec.missing_ok:
        body.append("    missingok")
    if spec.notif_empty:
        body.append("    notifempty")
    body.append(f"    create {spec.create_mode} {spec.create_user} {spec.create_group}")
    if spec.prerotate:
        body.append("    prerotate")
        for line in spec.prerotate.splitlines():
            body.append(f"        {line}")
        body.append("    endscript")
    if spec.postrotate:
        body.append("    postrotate")
        for line in spec.postrotate.splitlines():
            body.append(f"        {line}")
        body.append("    endscript")

    lines.extend(body)
    lines.append("}")

    content = _GENERATOR_COMMENT + "\n" + "\n".join(lines) + "\n"
    filename = f"ainews-{spec.name}.conf"

    return RenderedLogrotateRule(
        spec=spec,
        content=content,
        filename=filename,
        install_path=Path("/etc/logrotate.d") / filename,
    )


def build_logrotate_rule(
    log_dir: Path,
    scope: str = "system",
) -> LogrotateRuleSpec:
    """Build a LogrotateRuleSpec for ainews file logs."""
    log_path = str(log_dir / "*.log")

    return LogrotateRuleSpec(
        name="ainews",
        log_paths=[log_path],
        frequency="daily",
        rotate_count=10,
        compress=True,
        delay_compress=True,
        missing_ok=True,
        notif_empty=True,
        create_mode="0640",
        create_user="root",
        create_group="adm",
        postrotate="systemctl reload ainews-web.service 2>/dev/null || true",
    )
