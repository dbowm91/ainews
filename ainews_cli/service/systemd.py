def build_docker_compose_unit(
    resolved_paths: Any,
    scope: ServiceScope = ServiceScope.USER,
    env_file: Path | None = None,
) -> ServiceUnitSpec:
    """Build a ServiceUnitSpec for Docker Compose deployment."""
    config = resolved_paths
    compose_dir = config.app_dir.path if hasattr(config, "app_dir") else Path.cwd()

    return ServiceUnitSpec(
        name="ainews",
        description="AI News (Docker Compose)",
        scope=scope,
        profile=ServiceProfile.DOCKER_COMPOSE,
        exec_start="docker compose up",
        exec_stop="docker compose down",
        working_directory=compose_dir,
        environment_file=env_file,
        restart_policy=RestartPolicy.ALWAYS,
        restart_sec=10,
        timeout_start_sec=180,
        timeout_stop_sec=60,
        user=None,
        after=["network.target", "docker.service"],
        requires=["docker.service"],
        syslog_identifier="ainews",
    )


def _find_cli_executable() -> str:
    """Find the ainews CLI executable path."""
    import shutil
    import sys

    ainews_path = shutil.which("ainews")
    if ainews_path:
        return ainews_path
    return f"{sys.executable} -m ainews_cli.main"
