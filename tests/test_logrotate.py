"""Tests for ainews_cli.service.logrotate — rule rendering and logrotate integration."""

from __future__ import annotations

from pathlib import Path

import pytest

from ainews_cli.service.logrotate import build_logrotate_rule, render_logrotate_rule
from ainews_cli.service.models import LogrotateRuleSpec


class TestLogrotateRuleSpec:
    def test_defaults(self):
        spec = LogrotateRuleSpec(
            name="test",
            log_paths=["/var/log/test.log"],
        )
        assert spec.frequency == "daily"
        assert spec.rotate_count == 10
        assert spec.compress is True
        assert spec.delay_compress is True
        assert spec.missing_ok is True
        assert spec.notif_empty is True
        assert spec.create_mode == "0640"
        assert spec.create_user == "root"
        assert spec.create_group == "adm"
        assert spec.postrotate is None
        assert spec.prerotate is None
        assert spec.size is None
        assert spec.maxsize is None

    def test_frozen(self):
        spec = LogrotateRuleSpec(
            name="test",
            log_paths=["/var/log/test.log"],
        )
        with pytest.raises(AttributeError):
            spec.name = "changed"

    def test_frozen_log_paths(self):
        spec = LogrotateRuleSpec(
            name="test",
            log_paths=["/var/log/test.log"],
        )
        with pytest.raises(AttributeError):
            spec.log_paths = ["/other"]


class TestRenderLogrotateRule:
    def _make_spec(self, **overrides) -> LogrotateRuleSpec:
        defaults = {
            "name": "ainews",
            "log_paths": ["/var/log/ainews/*.log"],
        }
        defaults.update(overrides)
        return LogrotateRuleSpec(**defaults)

    def test_basic_render(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        assert result.filename == "ainews-ainews.conf"
        assert "/var/log/ainews/*.log" in result.content
        assert "{" in result.content
        assert "}" in result.content

    def test_generator_comment(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        assert "Generated by ainews service manager" in result.content

    def test_daily_frequency(self):
        spec = self._make_spec(frequency="daily")
        result = render_logrotate_rule(spec)
        assert "daily" in result.content

    def test_weekly_frequency(self):
        spec = self._make_spec(frequency="weekly")
        result = render_logrotate_rule(spec)
        assert "weekly" in result.content

    def test_monthly_frequency(self):
        spec = self._make_spec(frequency="monthly")
        result = render_logrotate_rule(spec)
        assert "monthly" in result.content

    def test_compress_directive(self):
        spec = self._make_spec(compress=True)
        result = render_logrotate_rule(spec)
        assert "    compress" in result.content

    def test_no_compress_directive(self):
        spec = self._make_spec(compress=False)
        result = render_logrotate_rule(spec)
        assert "    compress\n" not in result.content
        # delaycompress should still be present when only compress is disabled
        assert "delaycompress" in result.content

    def test_delay_compress(self):
        spec = self._make_spec(delay_compress=True)
        result = render_logrotate_rule(spec)
        assert "delaycompress" in result.content

    def test_no_delay_compress(self):
        spec = self._make_spec(delay_compress=False)
        result = render_logrotate_rule(spec)
        assert "delaycompress" not in result.content

    def test_rotate_count(self):
        spec = self._make_spec(rotate_count=5)
        result = render_logrotate_rule(spec)
        assert "rotate 5" in result.content

    def test_rotate_count_zero(self):
        spec = self._make_spec(rotate_count=0)
        result = render_logrotate_rule(spec)
        assert "rotate 0" in result.content

    def test_size_threshold(self):
        spec = self._make_spec(size="100M")
        result = render_logrotate_rule(spec)
        assert "size 100M" in result.content

    def test_no_size_when_none(self):
        spec = self._make_spec(size=None)
        result = render_logrotate_rule(spec)
        assert "size " not in result.content

    def test_maxsize(self):
        spec = self._make_spec(maxsize="50M")
        result = render_logrotate_rule(spec)
        assert "maxsize 50M" in result.content

    def test_no_maxsize_when_none(self):
        spec = self._make_spec(maxsize=None)
        result = render_logrotate_rule(spec)
        assert "maxsize " not in result.content

    def test_create_mode(self):
        spec = self._make_spec(create_mode="0640", create_user="root", create_group="adm")
        result = render_logrotate_rule(spec)
        assert "create 0640 root adm" in result.content

    def test_create_mode_custom(self):
        spec = self._make_spec(create_mode="0755", create_user="www", create_group="www")
        result = render_logrotate_rule(spec)
        assert "create 0755 www www" in result.content

    def test_postrotate(self):
        spec = self._make_spec(postrotate="systemctl reload ainews 2>/dev/null || true")
        result = render_logrotate_rule(spec)
        assert "postrotate" in result.content
        assert "systemctl reload ainews" in result.content
        assert "endscript" in result.content

    def test_postrotate_multiline(self):
        spec = self._make_spec(postrotate="line1\nline2\nline3")
        result = render_logrotate_rule(spec)
        assert "line1" in result.content
        assert "line2" in result.content
        assert "line3" in result.content
        assert result.content.count("postrotate") == 1
        assert result.content.count("endscript") == 1

    def test_no_postrotate_when_none(self):
        spec = self._make_spec(postrotate=None)
        result = render_logrotate_rule(spec)
        assert "postrotate" not in result.content
        assert "endscript" not in result.content

    def test_prerotate(self):
        spec = self._make_spec(prerotate="echo rotating")
        result = render_logrotate_rule(spec)
        assert "prerotate" in result.content
        assert "echo rotating" in result.content
        assert "endscript" in result.content

    def test_prerotate_multiline(self):
        spec = self._make_spec(prerotate="line_a\nline_b")
        result = render_logrotate_rule(spec)
        assert "line_a" in result.content
        assert "line_b" in result.content

    def test_no_prerotate_when_none(self):
        spec = self._make_spec(prerotate=None)
        result = render_logrotate_rule(spec)
        assert "prerotate" not in result.content

    def test_install_path(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        assert str(result.install_path).startswith("/etc/logrotate.d/")
        assert result.install_path.name == "ainews-ainews.conf"

    def test_missing_ok(self):
        spec = self._make_spec(missing_ok=True)
        result = render_logrotate_rule(spec)
        assert "missingok" in result.content

    def test_no_missing_ok(self):
        spec = self._make_spec(missing_ok=False)
        result = render_logrotate_rule(spec)
        assert "missingok" not in result.content

    def test_notifempty(self):
        spec = self._make_spec(notif_empty=True)
        result = render_logrotate_rule(spec)
        assert "notifempty" in result.content

    def test_no_notifempty(self):
        spec = self._make_spec(notif_empty=False)
        result = render_logrotate_rule(spec)
        assert "notifempty" not in result.content

    def test_single_log_path(self):
        spec = self._make_spec(log_paths=["/var/log/a.log"])
        result = render_logrotate_rule(spec)
        assert "/var/log/a.log" in result.content
        lines = result.content.splitlines()
        log_line = lines[1]
        assert log_line == "/var/log/a.log"

    def test_multiple_log_paths(self):
        spec = self._make_spec(log_paths=["/var/log/a.log", "/var/log/b.log"])
        result = render_logrotate_rule(spec)
        assert "/var/log/a.log /var/log/b.log" in result.content

    def test_three_log_paths(self):
        spec = self._make_spec(log_paths=["/a.log", "/b.log", "/c.log"])
        result = render_logrotate_rule(spec)
        assert "/a.log /b.log /c.log" in result.content

    def test_spec_preserved_in_result(self):
        spec = self._make_spec(name="myservice")
        result = render_logrotate_rule(spec)
        assert result.spec is spec
        assert result.spec.name == "myservice"

    def test_filename_format(self):
        spec = self._make_spec(name="custom-name")
        result = render_logrotate_rule(spec)
        assert result.filename == "ainews-custom-name.conf"

    def test_content_ends_with_newline(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        assert result.content.endswith("\n")

    def test_all_directives_present_by_default(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        lines = result.content
        assert "daily" in lines
        assert "rotate 10" in lines
        assert "    compress" in lines
        assert "delaycompress" in lines
        assert "missingok" in lines
        assert "notifempty" in lines
        assert "create 0640 root adm" in lines

    def test_size_and_maxsize_together(self):
        spec = self._make_spec(size="200M", maxsize="100M")
        result = render_logrotate_rule(spec)
        assert "size 200M" in result.content
        assert "maxsize 100M" in result.content

    def test_both_prerotate_and_postrotate(self):
        spec = self._make_spec(
            prerotate="echo pre",
            postrotate="echo post",
        )
        result = render_logrotate_rule(spec)
        assert "prerotate" in result.content
        assert "postrotate" in result.content
        assert "echo pre" in result.content
        assert "echo post" in result.content

    def test_content_structure(self):
        spec = self._make_spec()
        result = render_logrotate_rule(spec)
        lines = result.content.splitlines()
        assert lines[0].startswith("# Generated by")
        assert lines[1] == "/var/log/ainews/*.log"
        assert lines[2] == "{"
        assert lines[-1] == "}"
        # All body lines should be indented
        for line in lines[3:-1]:
            assert line.startswith("    ") or line == ""


class TestBuildLogrotateRule:
    def test_build_default(self):
        spec = build_logrotate_rule(Path("/var/log/ainews"))
        assert spec.name == "ainews"
        assert "/var/log/ainews/*.log" in spec.log_paths[0]
        assert spec.frequency == "daily"
        assert spec.rotate_count == 10
        assert spec.compress is True
        assert spec.delay_compress is True
        assert spec.missing_ok is True
        assert spec.notif_empty is True

    def test_build_system_scope(self):
        spec = build_logrotate_rule(Path("/var/log/ainews"), scope="system")
        assert spec.create_user == "root"
        assert spec.create_group == "adm"
        assert spec.name == "ainews"

    def test_build_user_scope(self):
        spec = build_logrotate_rule(Path("/home/user/logs"), scope="user")
        assert spec.name == "ainews"
        assert "/home/user/logs/*.log" in spec.log_paths[0]

    def test_build_has_postrotate(self):
        spec = build_logrotate_rule(Path("/var/log/ainews"))
        assert spec.postrotate is not None
        assert "systemctl" in spec.postrotate

    def test_build_render_roundtrip(self):
        spec = build_logrotate_rule(Path("/var/log/ainews"))
        result = render_logrotate_rule(spec)
        assert "ainews-ainews.conf" == result.filename
        assert "/etc/logrotate.d/" in str(result.install_path)
        assert "daily" in result.content
        assert "rotate 10" in result.content
        assert "    compress" in result.content
        assert "postrotate" in result.content
