"""Systemd unit file rendering engine."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from ainews_cli.service.models import (
    RenderedUnit,
    RestartPolicy,
    ServiceProfile,
    ServiceScope,
    ServiceUnitSpec,
)

_GENERATOR_COMMENT = "# Generated by ainews service manager — do not edit manually"


def _systemd_bool(value: bool) -> str:
    return "true" if value else "false"


def _append_directives(lines: list[str], key: str, values: list[str]) -> None:
    if values:
        lines.append(f"{key}={' '.join(values)}")


def render_unit(spec: ServiceUnitSpec) -> RenderedUnit:
    """Render a ServiceUnitSpec into a systemd unit file content string."""
    sections: list[str] = []

    # [Unit] section
    unit_lines: list[str] = []
    unit_lines.append(f"Description={spec.description}")
    if spec.documentation:
        unit_lines.append(f"Documentation={spec.documentation}")
    _append_directives(unit_lines, "After", spec.after)
    _append_directives(unit_lines, "Requires", spec.requires)
    _append_directives(unit_lines, "Wants", spec.wants)
    _append_directives(unit_lines, "BindsTo", spec.binds_to)
    sections.append("[Unit]\n" + "\n".join(unit_lines))

    # [Service] section
    svc_lines: list[str] = []
    svc_lines.append("Type=simple")
    svc_lines.append(f"ExecStart={spec.exec_start}")
    if spec.exec_stop:
        svc_lines.append(f"ExecStop={spec.exec_stop}")
    if spec.exec_reload:
        svc_lines.append(f"ExecReload={spec.exec_reload}")
    if spec.working_directory:
        svc_lines.append(f"WorkingDirectory={spec.working_directory}")
    if spec.environment_file:
        svc_lines.append(f"EnvironmentFile={spec.environment_file}")
    svc_lines.append(f"Restart={spec.restart_policy.value}")
    svc_lines.append(f"RestartSec={spec.restart_sec}")
    svc_lines.append(f"TimeoutStartSec={spec.timeout_start_sec}")
    svc_lines.append(f"TimeoutStopSec={spec.timeout_stop_sec}")
    if spec.user:
        svc_lines.append(f"User={spec.user}")
    if spec.group:
        svc_lines.append(f"Group={spec.group}")
    svc_lines.append(f"StandardOutput={spec.standard_output}")
    svc_lines.append(f"StandardError={spec.standard_error}")
    if spec.syslog_identifier:
        svc_lines.append(f"SyslogIdentifier={spec.syslog_identifier}")
    # Hardening
    svc_lines.append(f"NoNewPrivileges={_systemd_bool(spec.no_new_privileges)}")
    svc_lines.append(f"PrivateTmp={_systemd_bool(spec.private_tmp)}")
    if spec.protect_system:
        svc_lines.append(f"ProtectSystem={spec.protect_system}")
    svc_lines.append(f"ProtectHome={_systemd_bool(spec.protect_home)}")
    svc_lines.append(f"UMask={spec.umask}")
    # Capability management
    if spec.capability_bounding_set is not None:
        svc_lines.append(f"CapabilityBoundingSet={spec.capability_bounding_set}")
    if spec.ambient_capabilities:
        svc_lines.append(f"AmbientCapabilities={spec.ambient_capabilities}")
    # Namespace restrictions
    if spec.restrict_namespaces:
        svc_lines.append("RestrictNamespaces=true")
    if spec.restrict_realtime:
        svc_lines.append("RestrictRealtime=true")
    if spec.restrict_suidsgid:
        svc_lines.append("RestrictSUIDSGID=true")
    # Memory and personality
    if spec.memory_deny_write_execute:
        svc_lines.append("MemoryDenyWriteExecute=true")
    if spec.lock_personality:
        svc_lines.append("LockPersonality=true")
    if spec.system_call_architectures:
        svc_lines.append(f"SystemCallArchitectures={spec.system_call_architectures}")
    # Network restrictions
    if spec.private_network:
        svc_lines.append("PrivateNetwork=true")
    # Device restrictions
    if spec.private_devices:
        svc_lines.append("PrivateDevices=true")
    # Kernel protection
    if spec.protect_kernel_tunables:
        svc_lines.append("ProtectKernelTunables=true")
    if spec.protect_kernel_modules:
        svc_lines.append("ProtectKernelModules=true")
    if spec.protect_control_groups:
        svc_lines.append("ProtectControlGroups=true")
    if spec.protect_clock:
        svc_lines.append("ProtectClock=true")
    # Address families
    if spec.restrict_address_families:
        svc_lines.append(f"RestrictAddressFamilies={spec.restrict_address_families}")
    # System call filter
    if spec.system_call_filter:
        svc_lines.append(f"SystemCallFilter={spec.system_call_filter}")
    sections.append("[Service]\n" + "\n".join(svc_lines))

    # [Install] section
    install_lines: list[str] = []
    install_lines.append(f"WantedBy={spec.wanted_by}")
    sections.append("[Install]\n" + "\n".join(install_lines))

    content = _GENERATOR_COMMENT + "\n\n" + "\n\n".join(sections) + "\n"
    filename = f"{spec.name}.service"

    return RenderedUnit(
        spec=spec,
        content=content,
        filename=filename,
        install_path=_get_install_path(spec),
    )


def _get_install_path(spec: ServiceUnitSpec) -> Path:
    """Determine the installation path for a unit file."""
    if spec.scope == ServiceScope.USER:
        return Path.home() / ".config" / "systemd" / "user" / f"{spec.name}.service"
    return Path("/etc") / "systemd" / "system" / f"{spec.name}.service"


def build_web_unit(
    resolved_paths: Any,
    scope: ServiceScope = ServiceScope.USER,
    profile: ServiceProfile = ServiceProfile.BARE_METAL,
    env_file: Path | None = None,
) -> ServiceUnitSpec:
    """Build a ServiceUnitSpec for the ainews web process."""
    config = resolved_paths
    import sys
    cli_exec = _find_cli_executable()

    return ServiceUnitSpec(
        name="ainews-web",
        description="AI News web application",
        scope=scope,
        profile=profile,
        exec_start=f"{sys.executable} run.py",
        exec_reload=f"{cli_exec} config check",
        working_directory=config.app_dir.path if hasattr(config, "app_dir") else None,
        environment_file=env_file,
        restart_policy=RestartPolicy.ON_FAILURE,
        restart_sec=5,
        timeout_start_sec=120,
        timeout_stop_sec=30,
        user=None,
        after=["network.target", "redis.service"],
        wants=["ainews-celery-worker.service", "ainews-celery-beat.service"],
        requires=[],
        syslog_identifier="ainews-web",
    )


def build_celery_worker_unit(
    resolved_paths: Any,
    scope: ServiceScope = ServiceScope.USER,
    profile: ServiceProfile = ServiceProfile.BARE_METAL,
    env_file: Path | None = None,
) -> ServiceUnitSpec:
    """Build a ServiceUnitSpec for the Celery worker."""
    config = resolved_paths
    import sys

    return ServiceUnitSpec(
        name="ainews-celery-worker",
        description="AI News Celery worker",
        scope=scope,
        profile=profile,
        exec_start=f"{sys.executable} -m celery -A celery_app:celery_app worker -l info --concurrency=2",
        working_directory=config.app_dir.path if hasattr(config, "app_dir") else None,
        environment_file=env_file,
        restart_policy=RestartPolicy.ON_FAILURE,
        restart_sec=10,
        timeout_start_sec=120,
        timeout_stop_sec=60,
        user=None,
        after=["network.target", "redis.service", "ainews-web.service"],
        binds_to=["ainews-web.service"],
        syslog_identifier="ainews-celery-worker",
    )


def build_celery_beat_unit(
    resolved_paths: Any,
    scope: ServiceScope = ServiceScope.USER,
    profile: ServiceProfile = ServiceProfile.BARE_METAL,
    env_file: Path | None = None,
) -> ServiceUnitSpec:
    """Build a ServiceUnitSpec for the Celery beat scheduler."""
    config = resolved_paths
    import sys
    from pathlib import Path

    state_dir = getattr(config, "state_dir", None)
    state_path = getattr(state_dir, "path", None)
    schedule_dir = Path(state_path) if isinstance(state_path, (str, Path)) else Path(config.app_dir.path) / "instance"

    return ServiceUnitSpec(
        name="ainews-celery-beat",
        description="AI News Celery beat scheduler",
        scope=scope,
        profile=profile,
        exec_start=(f"{sys.executable} -m celery -A celery_app:celery_app beat -l info "
                    f"--schedule={schedule_dir / 'celerybeat-schedule'}"),
        working_directory=config.app_dir.path if hasattr(config, "app_dir") else None,
        environment_file=env_file,
        restart_policy=RestartPolicy.ON_FAILURE,
        restart_sec=10,
        timeout_start_sec=60,
        timeout_stop_sec=30,
        user=None,
        after=["network.target", "redis.service", "ainews-web.service"],
        binds_to=["ainews-web.service"],
        syslog_identifier="ainews-celery-beat",
    )


def build_docker_compose_unit(
    resolved_paths: Any,
    scope: ServiceScope = ServiceScope.USER,
    env_file: Path | None = None,
) -> ServiceUnitSpec:
    """Build a ServiceUnitSpec for Docker Compose deployment."""
    config = resolved_paths
    compose_dir = config.app_dir.path if hasattr(config, "app_dir") else Path.cwd()

    return ServiceUnitSpec(
        name="ainews",
        description="AI News (Docker Compose)",
        scope=scope,
        profile=ServiceProfile.DOCKER_COMPOSE,
        exec_start="docker compose up",
        exec_stop="docker compose down",
        working_directory=compose_dir,
        environment_file=env_file,
        restart_policy=RestartPolicy.ALWAYS,
        restart_sec=10,
        timeout_start_sec=180,
        timeout_stop_sec=60,
        user=None,
        after=["network.target", "docker.service"],
        requires=["docker.service"],
        syslog_identifier="ainews",
    )


def _find_cli_executable() -> str:
    """Find the ainews CLI executable path."""
    import shutil
    import sys

    ainews_path = shutil.which("ainews")
    if ainews_path:
        return ainews_path
    return f"{sys.executable} -m ainews_cli.main"
